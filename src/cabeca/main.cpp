int totalKeyFrames = sizeof(roteiro) / sizeof(roteiro[0]);
int frameAtual = 0;
unsigned long inicioDoShow;

void setup() {

  olhosC.inicializar();
  bocaC.inicializar();
  //pescocoC.incializar();
  inicioDoShow = millis();
}

void loop() {
  unsigned long tempoDecorrido = millis() - inicioDoShow;

  if (frameAtual < totalKeyFrames && tempoDecorrido >= roteiro[frameAtual].tempo) {

    // 1. Aplica o movimento dos olhos
    olhosC.mover(roteiro[frameAtual].olhosX, roteiro[frameAtual].olhosY);

    // 2. Aplica a abertura proporcional da boca direto, sem if/else!
    // Nota: Lembre-se de usar o nome da função que criamos para converter 0-100% 
    // nos ângulos da boca (no passo anterior chamamos de falarPorcento).
    bocaC.falarPorcento(roteiro[frameAtual].boca);

    // Passa para o próximo frame
    frameAtual++;
  }
}
